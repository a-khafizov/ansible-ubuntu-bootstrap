#!/bin/bash

echo "Генерация SSH-ключа"

# Параметры по умолчанию
KEY_PATH="$HOME/.ssh/id_ed25519"


# 1. Генерация ключа Ed25519 без комментария и без пароля
echo "Создаю ключ $KEY_PATH..."
ssh-keygen -t ed25519 -f "$KEY_PATH" -N ""


# 2. Запуск SSH‑агента и добавление ключа
echo "Запускаю SSH‑агент и добавляю ключ..."
eval "$(ssh-agent -s)"
ssh-add "$KEY_PATH"


# 3. Вывод публичного ключа
echo ""
echo "Ваш публичный ключ (скопируйте его на сервер):"
echo "-------------------------------------------"
cat "$KEY_PATH.pub"
echo "-------------------------------------------"

# 4. Краткие инструкции
echo ""
echo "Что делать дальше:"
echo "1. Скопируйте ключ выше."
echo "2. Добавьте его в ~/.ssh/authorized_keys на сервере"
echo "   или в настройки SSH‑сервиса (GitHub, GitLab и т.п.)."
echo "3. Для подключения используйте:"
echo "   ssh user@hostname              # если порт 22"
echo "   ssh -p PORT user@hostname      # если порт не 22"
